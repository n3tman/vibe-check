def test_activity_metrics():
    commits = [
        c("Ada", days=1), c("Ada", days=2), c("Bob", "bob@example.org", days=5),
        c("Cy", "cy@example.org", days=60), c("Ada", days=400),
        c("copilot-swe-agent[bot]", "198982749+copilot-swe-agent[bot]@users.noreply.github.com", days=3),
        c("dependabot[bot]", "49699333+dependabot[bot]@users.noreply.github.com", days=1),
    ]
    m = Activity(commits, NOW).metrics()
    assert m["commits_30d"] == 4  # the AI agent's commit counts, dependabot's does not
    assert m["commits_90d"] == 5
    assert m["authors_90d"] == 3  # the AI agent is not an author
    assert m["authors_all"] == 3
    assert m["bus_factor_365d"] == 1
    assert len(m["weekly_commits"]) == 52 and sum(m["weekly_commits"]) == 5
    assert sum(m["daily_commits"].values()) == 5
    assert list(m["authors_by_quarter"])[-1] == "2026-Q4"


