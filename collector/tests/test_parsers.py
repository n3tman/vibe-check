def test_first_responses():
    t0 = NOW - timedelta(days=10)
    issues = [{"number": 1, "created": t0, "author": "u"}, {"number": 2, "created": t0, "author": "v"}]
    comments = [
        {"number": 1, "created": t0 + timedelta(hours=1), "author": "u"},  # the author's own
        {"number": 1, "created": t0 + timedelta(hours=2), "author": "github-actions[bot]"},
        {"number": 1, "created": t0 + timedelta(days=2), "author": "maint"},
        {"number": 1, "created": t0 + timedelta(days=1), "author": "other"},
    ]
    pairs = forges._first_responses(issues, comments)
    assert forges._median_days(pairs) == (1.0, 2, 1)


class FakeHttp:
    def __init__(self, routes):
        self.routes, self.calls = routes, 0

    def get(self, url, headers=None, tries=3):
        for prefix, (body, hdr) in self.routes.items():
            if url.startswith(prefix):
                return body, hdr
        raise AssertionError(url)


def test_github_reader_shapes():
    api = "https://api.github.com/repos/o/r"
    http = FakeHttp({
        api + "/languages": ({"TypeScript": 900, "CSS": 100}, {}),
        api + "/pulls": ([{}], {"link": f'<{api}/pulls?state=open&per_page=1&page=2>; rel="next", <{api}/pulls?state=open&per_page=1&page=7>; rel="last"'}),
        api + "/issues/comments": ([], {}),
        api + "/issues": ([], {}),
        api: ({"stargazers_count": 5, "forks_count": 2, "archived": False, "license": {"spdx_id": "MIT"}, "open_issues_count": 10, "has_issues": True}, {}),
    })
    out = forges.github(http, "https://github.com/o/r", NOW)
    assert out["stars"] == 5 and out["open_prs"] == 7 and out["open_issues"] == 3
    assert out["languages"] == {"TypeScript": 0.9, "CSS": 0.1} and out["licence_detected"] == "MIT"
    assert out["issues_sampled"] == 0 and out["issue_first_response_median_days"] is None


def test_fetch_never_raises():
    class Boom:
        calls = 0

        def get(self, *a, **k):
            raise OSError("down")

    out = forges.fetch("github", "https://github.com/o/r", Boom(), NOW)
    assert out["stars"] is None and "down" in out["api_error"]
    assert forges.fetch("sourcehut", "https://git.sr.ht/~a/b", Boom(), NOW)["api_error"].startswith("no API reader")
