# --- author dedup -----------------------------------------------------------------------

def test_authors_dedup_by_email_and_name():
    idx = AuthorIndex()
    ids = [("Ada Lovelace", "ada@work.example"), ("Ada Lovelace", "ada@home.example"), ("ada", "ada@home.example"), ("Bob", "bob@example.org"),
           ("ada", "12345+ada@users.noreply.github.com"), ("Ada L", "ada@users.noreply.github.com")]
    for n, e in ids:
        idx.add(n, e)
    keys = {idx.key(n, e) for n, e in ids}
    assert len(keys) == 2  # every Ada identity joins (shared emails, the name "ada", the login), and Bob
    assert idx.key("ada", "12345+ada@users.noreply.github.com") == idx.key("Ada L", "ada@users.noreply.github.com")


def test_weak_names_do_not_join():
    idx = AuthorIndex()
    idx.add("root", "a@example.org")
    idx.add("root", "b@example.org")
    assert idx.key("root", "a@example.org") != idx.key("root", "b@example.org")


