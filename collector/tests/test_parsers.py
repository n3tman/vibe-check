def test_unique_changes():
    from vibecheck.activity import unique_changes

    written = NOW - timedelta(days=40)
    a = Commit("a1", "Ada", "ada@example.org", "Ada", "ada@example.org", NOW - timedelta(days=3), "fix(x): y", written)
